"""build.ninja and objdiff.json for PS2 3.0.1 build 198 (configure.py --mwcc --version PS2_3_0_1b198).

The build, in the order ninja runs it:

  1. fetch the original (decomp.me's image of it), the tools (delink, objdiff-cli, wibo) and the host compiler and
     linker (tools/download_tool.py);
  2. make the five C library files that are Metrowerks' own text from CodeWarrior 9.2's library sources and their
     patches (msl.py, config/PS2_3_0_1b198/msl);
  3. describe the original for delink and split it into one object per unit (describe.py, with
     config/PS2_3_0_1b198/symbols.txt and splits.txt);
  4. compile every source of config/PS2_3_0_1b198/sources.json with CodeWarrior 9.2's x86 compiler under wibo;
  5. compare each compiled object with its split one (objdiff-cli) and check where its relocations point
     (check_relocs.py): build/PS2_3_0_1b198/report.json. The build fails when a unit marked Matching is not exact
     (report.py);
  6. link the original back together, each unit marked Matching from its compiled object, and check it against the
     original's SHA-1 (link_config.py, split.py, link.py): build/PS2_3_0_1b198/mwccps2.exe.

The original comes from decomp.me's public image of the compiler (tools/download_tool.py ps2_b198), into
build/compilers/PS2/3.0.1b198, checked by its SHA-256.
"""

from __future__ import annotations

import json
import shlex
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import b198  # noqa: E402
from mw import project  # noqa: E402

import msl  # noqa: E402

# -enum min: the original's enums are the smallest integer type that holds their values. MWCCPS2_B198 picks the
# version's text in the files it shares with the others (tools/mwccps2/merge.py).
CFLAGS = ["-O4,p", "-inline", "auto,deferred", "-enum", "min"]
DEFINES = [f"-DVERSION={b198.VERSION.index}", "-DMWCCPS2_B198=1"]
COMPILER = "build/compilers/cw92/mwcc.exe"
LINKER = "build/compilers/cw94/mwld.exe"
TOOLS = "tools/mwccps2"


def pool(source: str) -> str:
    return "stem_" + "".join(ch if ch.isalnum() else "_" for ch in Path(source).stem)


def generate() -> str:
    v = b198.VERSION
    config, build = project.relative(b198.CONFIG), project.relative(b198.BUILD)
    original = project.relative(b198.ORIGINAL)
    wibo = "build/tools/wibo"
    python = shlex.quote(sys.executable)
    sources = b198.sources()
    out = [
        "# Generated by configure.py",
        f"python = {python}",
        "",
        "pool downloads",
        "  depth = 1",
        "rule download",
        "  command = $python tools/download_tool.py $tool $out",
        "  description = DOWNLOAD $out",
        "  pool = downloads",
        "",
    ]
    for tool, path in (("delink", "build/tools/delink"), ("objdiff-cli", "build/tools/objdiff-cli"), ("wibo", wibo)):
        out += [f"build {path}: download", f"  tool = {tool}"]
    out += [f"build {COMPILER}: download", "  tool = cw92", f"build {LINKER}: download", "  tool = cw94_mwld", ""]
    out += [f"build {original}: download", "  tool = ps2_b198", ""]
    generated = [f"{msl.OUTPUT}/{name}" for name in msl.FILES]
    patches = [project.relative(msl.PATCHES / f"{name}.patch") for name in msl.FILES]
    out += [
        "build build/msl92/ok: download",
        "  tool = msl92",
        "rule msl",
        f"  command = $python {TOOLS}/msl.py apply build/msl92/MSL",
        "  description = MAKE the C library's files",
        f"build {' '.join(generated)}: msl build/msl92/ok | {TOOLS}/msl.py {' '.join(patches)}",
        "",
    ]
    out += [
        "rule describe",
        f"  command = $python {TOOLS}/describe.py {original} {config}/symbols.txt {config}/splits.txt {build}/delink",
        "  description = DESCRIBE the original",
        f"build {build}/delink/symbols.json {build}/delink/splits.json: describe {original} {config}/symbols.txt "
        f"{config}/splits.txt | {TOOLS}/describe.py",
        "rule split",
        f"  command = build/tools/delink ida-split {build}/delink/symbols.json {original} --idapro "
        f"{build}/delink/splits.json -o {build}/obj > {build}/split.log 2>&1 && touch $out",
        "  description = SPLIT the original",
        f"build {build}/obj/ok: split {build}/delink/symbols.json {build}/delink/splits.json | build/tools/delink",
        "rule relocs",
        f'  command = $python {TOOLS}/check_relocs.py $unit > $out.part; echo "exit $$?" >> $out.part; mv $out.part $out',
        "  description = RELOCS $unit",
        # (the compiler writes STEM.dep where it runs: one pool a stem, so two units of one name take turns)
        "rule mwcc",
        f"  command = {wibo} {COMPILER} $cflags -MD -c $in -o $out && $python tools/transform_dep.py $stem.dep $out",
        "  description = MWCC $in",
        "  depfile = $out.d",
        "  deps = gcc",
        *(line for stem in sorted({pool(s) for s in sources}) for line in (f"pool {stem}", "  depth = 1")),
        "",
    ]
    objects, matching, checks, units = [], [], [], []
    for source, settings in sources.items():
        obj = f"{build}/{Path(source).with_suffix('.obj').as_posix()}"
        objects.append(obj)
        if settings.get("status") == "Matching":
            matching.append(obj)
        name = b198.unit_name(source)
        check = f"{build}/relocs/{name}.txt"
        checks.append(check)
        flags = list(CFLAGS)
        if settings.get("replace_inline"):  # the unit's own -inline options replace the global ones
            while "-inline" in flags:
                i = flags.index("-inline")
                del flags[i : i + 2]
        flags += settings.get("flags", []) + DEFINES + ["-I-"]  # the paths after -I- serve <...> includes too
        for directory in settings.get("include_dirs", b198.INCLUDE_DIRS):
            flags += ["-i", directory]
        out += [
            f"build {obj}: mwcc {source} | {COMPILER} {wibo}",
            f"  cflags = {shlex.join(flags)}",
            f"  stem = {Path(source).stem}",
            f"  pool = {pool(source)}",
            f"build {check}: relocs {obj} {build}/obj/ok | {TOOLS}/check_relocs.py {config}/symbols.txt "
            f"{config}/splits.txt {original}",
            f"  unit = {name}",
        ]
        units.append(
            {
                "name": name,
                "target_path": f"{build}/obj/{Path(source).with_suffix('.obj').as_posix()}",
                "base_path": obj,
                "metadata": {"source_path": source, "complete": settings.get("status") == "Matching"},
            }
        )
    link = f"{build}/link"
    out += [
        "",
        "rule report",
        f"  command = build/tools/objdiff-cli report generate -o $out > /dev/null 2>&1 && "
        f"$python {TOOLS}/report.py $out",
        "  description = COMPARE",
        f"build {build}/report.json: report {build}/obj/ok {' '.join(objects)} | build/tools/objdiff-cli "
        f"objdiff.json {TOOLS}/report.py {config}/sources.json {' '.join(checks)}",
        "rule link_config",
        f"  command = $python {TOOLS}/link_config.py > /dev/null",
        "  description = CONFIGURE the link",
        f"build {link}/symbols.txt {link}/splits.txt {link}/exports.txt: link_config {config}/symbols.txt "
        f"{config}/splits.txt {build}/delink/symbols.json | {original} {TOOLS}/link_config.py",
        "rule link_split",
        f"  command = $python {TOOLS}/split.py {wibo} {LINKER}",
        "  description = SPLIT the original for the link",
        f"build {link}/obj/ok: link_split {link}/symbols.txt {link}/splits.txt | {original} {TOOLS}/split.py "
        f"{LINKER} {wibo}",
        "rule link",
        f"  command = $python {TOOLS}/link.py {wibo} {LINKER}",
        "  description = LINK",
        f"build {link}/ok: link {link}/obj/ok {link}/exports.txt {' '.join(matching)} | {config}/sources.json "
        f"{TOOLS}/link.py {LINKER}",
        "rule configure",
        f"  command = $python configure.py --mwcc --version {v}",
        "  generator = 1",
        f"build build.ninja: configure | configure.py {TOOLS}/matching.py {config}/sources.json {config}/config.json",
        f"build {build}/ok: phony {build}/report.json {link}/ok",
        f"default {build}/ok",
        "",
    ]
    objdiff = {
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["*.c", "*.cpp", "*.h", "*.json", "*.txt"],
        "units": units,
    }
    project.write_atomic(project.ROOT / "objdiff.json", json.dumps(objdiff, indent=2) + "\n")
    return "\n".join(out)
